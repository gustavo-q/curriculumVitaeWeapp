/**
 * 区块标题 / 话题 → 文章 id。按顺序匹配，先命中的生效。
 * 编辑器传来的是区块标题（教育背景、实习经历、项目经历…），也可能是 base（基本信息）。
 */
const TOPIC_RULES = [
  { re: /教育|学历|学校|在校/, id: 'education' },
  { re: /自我评价|个人总结|个人优势|自我介绍|关于我|评价/, id: 'summary' },
  { re: /技能|证书|荣誉|奖项|获奖|语言|专长/, id: 'skills' },
  { re: /工作|实习|项目|经历|实践|校园|社团|作品/, id: 'star' },
  { re: /求职意向|关键词|JD|匹配/i, id: 'keywords' },
  { re: /^base$|基本信息|个人信息|照片|头像|证件照/i, id: 'photo' },
  { re: /命名|文件名/, id: 'naming' },
  { re: /一页|排版|版面|页数/, id: 'onepage' },
  { re: /避坑|检查|错误/, id: 'mistakes' }
]

function getArticle (id) {
  return ARTICLES.find((a) => a.id === id) || null
}

/** 按话题找最相关的一篇；找不到返回 null（页面退回列表） */
function findArticleByTopic (topic) {
  const s = String(topic == null ? '' : topic).trim()
  if (!s) return null
  const direct = getArticle(s)
  if (direct) return direct
  for (const r of TOPIC_RULES) {
    if (r.re.test(s)) return getArticle(r.id)
  }
  return null
}

const CATS = ['全部'].concat(ARTICLES.reduce((acc, a) => (acc.indexOf(a.cat) >= 0 ? acc : acc.concat([a.cat])), []))

module.exports = { ARTICLES, CATS, TOPIC_RULES, getArticle, findArticleByTopic }
